/** Дерево папок преимуществ: строится и валидируется rules-engine. */
function assembleTraits(): readonly TraitEntryDto[] {
  const groupsResult = SheetGroups.create(
    Object.keys(TRAITS),
    [
      {
        kind: "group",
        id: "g-racial",
        name: "Расовые черты",
        note: "Врождённые особенности бесов",
        children: [
          { kind: "item", entityId: "racial-material-resistance" },
          { kind: "item", entityId: "racial-claws" },
          { kind: "item", entityId: "racial-eidetic-memory" },
          { kind: "item", entityId: "racial-fit" },
          { kind: "item", entityId: "racial-dr" },
          { kind: "item", entityId: "racial-night-vision" },
          { kind: "item", entityId: "racial-flight" },
          { kind: "item", entityId: "racial-bestial" },
          { kind: "item", entityId: "racial-cannot-speak" },
          { kind: "item", entityId: "racial-demophobia" },
        ],
      },
      {
        kind: "group",
        id: "g-magic",
        name: "Магический дар",
        note: null,
        children: [
          { kind: "item", entityId: "magic-magery" },
          { kind: "item", entityId: "magic-mana-pool" },
          { kind: "item", entityId: "magic-innate-attack" },
        ],
      },
      {
        kind: "group",
        id: "g-character",
        name: "Черты характера",
        note: null,
        children: [
          { kind: "item", entityId: "char-congenial" },
          { kind: "item", entityId: "char-acute-taste-smell" },
          { kind: "item", entityId: "char-acute-hearing" },
          { kind: "item", entityId: "char-acute-vision" },
          { kind: "item", entityId: "char-skinny" },
          { kind: "item", entityId: "char-kleptomania" },
          { kind: "item", entityId: "char-berserk" },
          { kind: "item", entityId: "char-curious" },
        ],
      },
    ],
  );
  if (!groupsResult.ok) throw new Error(groupsResult.error.message);

  const serialize = (
    children: readonly ReturnType<SheetGroups["groups"]>[number][],
  ): TraitEntryDto[] =>
    children.map((child) => {
      if (child.kind === "group") {
        return {
          kind: "container",
          id: child.id,
          name: child.name,
          note: child.note,
          entries: serialize(child.children),
        };
      }
      const trait = TRAITS[child.entityId];
      if (trait === undefined) throw new Error(`Missing mock trait: ${child.entityId}`);
      return trait;
    });

  return serialize(groupsResult.value.groups());
}

